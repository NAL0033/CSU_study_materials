	jr $ra

# ------------------------------------------------------------
# strip_newline �� ȥ���ַ���ĩβ�Ļ��з� '\n'
# ���: $a0 = �ַ�����ַ
# ����: �ޣ�ԭ���޸ģ�
# �ƻ�: $t0, $t1
# ------------------------------------------------------------
strip_newline:
	move $t0, $a0            # $t0 = string start (saved as boundary)
	move $t1, $a0
strip_find_end:
	lb $t2, 0($t1)
	beqz $t2, strip_loop
	addiu $t1, $t1, 1
	j strip_find_end
strip_loop:
	beq $t1, $t0, strip_done # safety: don't go before buffer start
	addiu $t1, $t1, -1       # back up one char
	lb $t2, 0($t1)
	li $t3, '\n'
	beq $t2, $t3, strip_clear
	li $t3, '\r'
	beq $t2, $t3, strip_clear
	li $t3, ' '
	beq $t2, $t3, strip_clear
	j strip_done              # non-whitespace -> done
strip_clear:
	sb $zero, 0($t1)
	j strip_loop
strip_done:
	jr $ra

