	move $t0, $a0
	move $t1, $a1
strcmp_loop:
	lb $t2, 0($t0)
	lb $t3, 0($t1)
	bne $t2, $t3, strcmp_neq
	beqz $t2, strcmp_eq      # ����������β��
	addiu $t0, $t0, 1
	addiu $t1, $t1, 1
	j strcmp_loop
strcmp_eq:
	li $v0, 0
	jr $ra
