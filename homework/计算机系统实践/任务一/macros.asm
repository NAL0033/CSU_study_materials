op_to_char:
	li $t0, 1
	beq $a0, $t0, opc_plus
	li $t0, 2
	beq $a0, $t0, opc_minus
	li $t0, 3
	beq $a0, $t0, opc_mul
	li $t0, 4
	beq $a0, $t0, opc_div
