STACKS  SEGMENT STACK
    DW  100h DUP(?)
STACKS  ENDS

DATAS   SEGMENT
    KEYWORD_BUFFER    DB 20, 0, 20 DUP(0)
    SENTENCE_BUFFER   DB 80, 0, 80 DUP(0)

    MSG_KEYWORD       DB 0DH, 0AH, 'Enter keyword: $'
    MSG_SENTENCE      DB 0DH, 0AH, 'Enter Sentence: $'
    MSG_MATCH         DB 0DH, 0AH, 'Match at location: $'
    MSG_NOMATCH       DB 0DH, 0AH, 'No match.$'
    MSG_HEX_SUFFIX    DB 'H of the sentence.$'

    KEYWORD_LEN       DW ?
    SENTENCE_LEN      DW ?
    MATCH_POS         DW ?
    FOUND_FLAG        DB 0

    HEX_BUFFER        DB 5 DUP(' '), 0
DATAS   ENDS

CODES   SEGMENT
ASSUME  CS:CODES, DS:DATAS, SS:STACKS, ES:DATAS

MAIN PROC FAR
START:
    MOV AX, DATAS
    MOV DS, AX
    MOV ES, AX
    CLD

    LEA DX, MSG_KEYWORD
    MOV AH, 09h
    INT 21h
    LEA DX, KEYWORD_BUFFER
    CALL INPUT_STRING

    MOV AL, [KEYWORD_BUFFER+1]
    CBW
    MOV KEYWORD_LEN, AX

MAIN_LOOP:
    LEA DX, MSG_SENTENCE
    MOV AH, 09h
    INT 21h
    LEA DX, SENTENCE_BUFFER
    CALL INPUT_STRING

    MOV AL, [SENTENCE_BUFFER+1]
    CMP AL, 1
    JNE NOT_CTRL_C
    MOV AL, [SENTENCE_BUFFER+2]
    CMP AL, 3
    JE  EXIT_PROGRAM

NOT_CTRL_C:
    MOV AL, [SENTENCE_BUFFER+1]
    CBW
    MOV SENTENCE_LEN, AX

    MOV AX, SENTENCE_LEN
    CMP AX, KEYWORD_LEN
    JB  NOT_FOUND

    CALL FIND_SUBSTRING
    JMP CHECK_RESULT

NOT_FOUND:
    MOV FOUND_FLAG, 0

CHECK_RESULT:
    CMP FOUND_FLAG, 0
    JE  DISPLAY_NOMATCH

    LEA DX, MSG_MATCH
    MOV AH, 09h
    INT 21h

    MOV AX, MATCH_POS
    CALL PRINT_HEX

    LEA DX, MSG_HEX_SUFFIX
    MOV AH, 09h
    INT 21h
    JMP MAIN_LOOP

DISPLAY_NOMATCH:
    LEA DX, MSG_NOMATCH
    MOV AH, 09h
    INT 21h
    JMP MAIN_LOOP

MAIN ENDP

INPUT_STRING PROC NEAR
    PUSH AX
    PUSH CX
    PUSH SI

    MOV AH, 0Ah
    INT 21h

    MOV SI, DX
    ADD SI, 1
    MOV CL, [SI]
    XOR CH, CH
    INC SI
    ADD SI, CX
    MOV BYTE PTR [SI], '$'

    POP SI
    POP CX
    POP AX
    RET
INPUT_STRING ENDP

FIND_SUBSTRING PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI

    MOV FOUND_FLAG, 0

    MOV AX, SENTENCE_LEN
    SUB AX, KEYWORD_LEN
    INC AX
    MOV DX, AX
    CMP DX, 0
    JBE FS_END

    LEA BX, SENTENCE_BUFFER+2

FS_LOOP:
    PUSH BX

    LEA SI, KEYWORD_BUFFER+2
    MOV DI, BX

    MOV AX, KEYWORD_LEN
    MOV CX, AX

    REPE CMPSB
    JZ  FS_MATCH

    POP BX
    INC BX
    DEC DX
    JNZ FS_LOOP
    JMP FS_END

FS_MATCH:
    MOV FOUND_FLAG, 1
    POP BX
    MOV AX, BX
    SUB AX, OFFSET SENTENCE_BUFFER+2
    INC AX
    MOV MATCH_POS, AX

FS_END:
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
FIND_SUBSTRING ENDP

PRINT_HEX PROC NEAR
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH AX

    MOV BX, OFFSET HEX_BUFFER+4
    MOV BYTE PTR [BX], '$'
    DEC BX
    MOV CX, 4

PH_LOOP:
    XOR DX, DX
    MOV SI, 16
    DIV SI
    CMP DL, 9
    JBE PH_DIGIT
    ADD DL, 7
PH_DIGIT:
    ADD DL, '0'
    MOV [BX], DL
    DEC BX
    LOOP PH_LOOP

    LEA SI, HEX_BUFFER
    MOV CX, 4
SKIP_ZERO:
    MOV AL, [SI]
    CMP AL, '0'
    JNE FOUND_NONZERO
    INC SI
    LOOP SKIP_ZERO

    LEA DX, HEX_BUFFER+3
    JMP PH_PRINT

FOUND_NONZERO:
    MOV DX, SI

PH_PRINT:
    MOV AH, 09h
    INT 21h

    POP AX
    POP SI
    POP DX
    POP CX
    POP BX
    RET
PRINT_HEX ENDP

EXIT_PROGRAM:
    MOV AX, 4C00h
    INT 21h

CODES   ENDS
END START
